/// Trạng thái biên bản kiểm kê quỹ hằng năm (`LedgerAnnualAuditStatus`).
enum LedgerAnnualAuditStatusEnum {
  matched('Matched', 'Khớp số dư'),
  discrepancyDetected('DiscrepancyDetected', 'Phát hiện lệch');

  final String code;
  final String displayName;

  const LedgerAnnualAuditStatusEnum(this.code, this.displayName);

  static LedgerAnnualAuditStatusEnum fromCode(String? code) {
    if (code == null || code.trim().isEmpty) {
      return LedgerAnnualAuditStatusEnum.matched;
    }
    final normalized = code.trim().toLowerCase();
    for (final value in LedgerAnnualAuditStatusEnum.values) {
      if (value.code.toLowerCase() == normalized) {
        return value;
      }
    }
    return LedgerAnnualAuditStatusEnum.matched;
  }

  Color get badgeBackgroundColor {
    switch (this) {
      case LedgerAnnualAuditStatusEnum.matched:
        return const Color(0xFFECFDF5);
      case LedgerAnnualAuditStatusEnum.discrepancyDetected:
        return const Color(0xFFFFFBEB);
    }
  }

  Color get badgeTextColor {
    switch (this) {
      case LedgerAnnualAuditStatusEnum.matched:
        return const Color(0xFF0F766E);
      case LedgerAnnualAuditStatusEnum.discrepancyDetected:
        return const Color(0xFFB45309);
    }
  }

  Color get badgeBorderColor {
    switch (this) {
      case LedgerAnnualAuditStatusEnum.matched:
        return const Color(0xFF99F6E4);
      case LedgerAnnualAuditStatusEnum.discrepancyDetected:
        return const Color(0xFFFDE68A);
    }
  }
}

double _parseAuditAmount(dynamic raw) {
  if (raw == null) return 0.0;
  if (raw is num) return raw.toDouble();
  if (raw is String) return double.tryParse(raw.trim()) ?? 0.0;
  return 0.0;
}

double? _parseNullableAuditAmount(dynamic raw) {
  if (raw == null) return null;
  if (raw is num) return raw.toDouble();
  if (raw is String && raw.trim().isNotEmpty) {
    return double.tryParse(raw.trim());
  }
  return null;
}

int _parseAuditInt(dynamic raw, [int fallback = 0]) {
  if (raw == null) return fallback;
  if (raw is int) return raw;
  if (raw is num) return raw.toInt();
  if (raw is String) return int.tryParse(raw.trim()) ?? fallback;
  return fallback;
}

DateTime _parseAuditDateTime(dynamic raw) {
  if (raw is DateTime) return raw;
  if (raw is String && raw.trim().isNotEmpty) {
    return DateTime.tryParse(raw.trim()) ?? DateTime.now();
  }
  return DateTime.now();
}

/// Payload gửi `POST /api/v1/ledger/annual-audit` (`AnnualLedgerAuditRequest`).
@immutable
class AnnualLedgerAuditRequestDto {
  final double actualBalance;
  final int? auditYear;
  final String? referenceTransactionId;
  final String? notes;
  final String? evidenceAttachmentUrl;

  const AnnualLedgerAuditRequestDto({
    required this.actualBalance,
    this.auditYear,
    this.referenceTransactionId,
    this.notes,
    this.evidenceAttachmentUrl,
  });

  Map<String, dynamic> toJson() {
    final trimmedRef = referenceTransactionId?.trim();
    final trimmedNotes = notes?.trim();
    final trimmedUrl = evidenceAttachmentUrl?.trim();

    return {
      'actualBalance': double.parse(actualBalance.toStringAsFixed(2)),
      if (auditYear != null) 'auditYear': auditYear,
      if (trimmedRef != null && trimmedRef.isNotEmpty)
        'referenceTransactionId': trimmedRef,
      if (trimmedNotes != null && trimmedNotes.isNotEmpty) 'notes': trimmedNotes,
      if (trimmedUrl != null && trimmedUrl.isNotEmpty)
        'evidenceAttachmentUrl': trimmedUrl,
    };
  }
}

/// Mô hình biên bản kiểm kê quỹ hằng năm (`LedgerAnnualAuditResponse`).
@immutable
class LedgerAnnualAuditModel {
  final String auditId;
  final String clanId;
  final int auditYear;
  final int nextPeriodYear;
  final DateTime auditDate;
  final double systemBalance;
  final double actualBalance;
  final double discrepancyAmount;
  final LedgerAnnualAuditStatusEnum auditStatus;
  final String? referenceTransactionId;
  final String? adjustmentRequestId;
  final String? closingTransactionId;
  final double? openingBalanceNextPeriod;
  final String auditorAccountId;
  final String? auditorDisplayName;
  final String? notes;
  final String? evidenceAttachmentUrl;
  final DateTime createdAt;
  final LedgerAdjustmentRequestModel? autoGeneratedAdjustmentRequest;
  final ImmutableLedgerEntryModel? closingLedgerEntry;

  const LedgerAnnualAuditModel({
    required this.auditId,
    required this.clanId,
    required this.auditYear,
    required this.nextPeriodYear,
    required this.auditDate,
    required this.systemBalance,
    required this.actualBalance,
    required this.discrepancyAmount,
    required this.auditStatus,
    this.referenceTransactionId,
    this.adjustmentRequestId,
    this.closingTransactionId,
    this.openingBalanceNextPeriod,
    this.auditorAccountId = '',
    this.auditorDisplayName,
    this.notes,
    this.evidenceAttachmentUrl,
    required this.createdAt,
    this.autoGeneratedAdjustmentRequest,
    this.closingLedgerEntry,
  });

  bool get isMatched => auditStatus == LedgerAnnualAuditStatusEnum.matched;
  bool get isSurplus => discrepancyAmount > 0;
  bool get isShortage => discrepancyAmount < 0;

  String get effectiveAuditorName {
    final name = auditorDisplayName?.trim();
    if (name != null && name.isNotEmpty) return name;
    return auditorAccountId.trim().isNotEmpty ? auditorAccountId : 'Trưởng tộc';
  }

  String get formattedAuditDate =>
      AppFormatters.formatDateTime(auditDate.toLocal());

  String get formattedSolarDate => AppFormatters.formatDate(auditDate.toLocal());

  String get formattedLunarDate {
    final lunar =
        VietnameseLunarCalendar.convertSolarToLunar(auditDate.toLocal());
    return '${lunar.toShortAnniversaryString()} ÂL';
  }

  factory LedgerAnnualAuditModel.fromJson(Map<String, dynamic> json) {
    final adjJson = json['autoGeneratedAdjustmentRequest'];
    final closingJson = json['closingLedgerEntry'];
    final auditYearVal = _parseAuditInt(json['auditYear'], DateTime.now().year);
    return LedgerAnnualAuditModel(
      auditId: json['auditId'] as String? ?? '',
      clanId: json['clanId'] as String? ?? '',
      auditYear: auditYearVal,
      nextPeriodYear: _parseAuditInt(json['nextPeriodYear'], auditYearVal + 1),
      auditDate: _parseAuditDateTime(json['auditDate']),
      systemBalance: _parseAuditAmount(json['systemBalance']),
      actualBalance: _parseAuditAmount(json['actualBalance']),
      discrepancyAmount: _parseAuditAmount(json['discrepancyAmount']),
      auditStatus:
          LedgerAnnualAuditStatusEnum.fromCode(json['auditStatus'] as String?),
      referenceTransactionId: json['referenceTransactionId'] as String?,
      adjustmentRequestId: json['adjustmentRequestId'] as String?,
      closingTransactionId: json['closingTransactionId'] as String?,
      openingBalanceNextPeriod:
          _parseNullableAuditAmount(json['openingBalanceNextPeriod']),
      auditorAccountId: json['auditorAccountId'] as String? ?? '',
      auditorDisplayName: json['auditorDisplayName'] as String?,
      notes: json['notes'] as String?,
      evidenceAttachmentUrl: json['evidenceAttachmentUrl'] as String?,
      createdAt: _parseAuditDateTime(json['createdAt']),
      autoGeneratedAdjustmentRequest: adjJson is Map<String, dynamic>
          ? LedgerAdjustmentRequestModel.fromJson(adjJson)
          : null,
      closingLedgerEntry: closingJson is Map<String, dynamic>
          ? ImmutableLedgerEntryModel.fromJson(closingJson)
          : null,
    );
  }
}
