import 'package:flutter_test/flutter_test.dart';

import 'package:familyfund_app/features/finance/data/models/ledger_adjustment_models.dart';
import 'package:familyfund_app/features/finance/data/models/ledger_annual_audit_models.dart';

void main() {
  group('AnnualLedgerAuditRequestDto', () {
    test('toJson rounds actualBalance and omits null/blank optional fields',
        () {
      const dto = AnnualLedgerAuditRequestDto(
        actualBalance: 99800000.456,
        auditYear: 2026,
        referenceTransactionId: '   ',
        notes: '   ',
        evidenceAttachmentUrl: '',
      );

      final json = dto.toJson();
      expect(json['actualBalance'], 99800000.46);
      expect(json['auditYear'], 2026);
      expect(json.containsKey('referenceTransactionId'), isFalse);
      expect(json.containsKey('notes'), isFalse);
      expect(json.containsKey('evidenceAttachmentUrl'), isFalse);
    });

    test('toJson trims optional fields when provided', () {
      const dto = AnnualLedgerAuditRequestDto(
        actualBalance: 98000000,
        auditYear: 2026,
        referenceTransactionId: '  LDGMWYQDWK15F5JSY  ',
        notes: '  Kiểm kê két từ đường  ',
        evidenceAttachmentUrl: ' /api/v1/ledger/evidence/123.pdf ',
      );

      final json = dto.toJson();
      expect(json['actualBalance'], 98000000.0);
      expect(json['auditYear'], 2026);
      expect(json['referenceTransactionId'], 'LDGMWYQDWK15F5JSY');
      expect(json['notes'], 'Kiểm kê két từ đường');
      expect(json['evidenceAttachmentUrl'], '/api/v1/ledger/evidence/123.pdf');
    });
  });

  group('LedgerAnnualAuditModel', () {
    test('parses Matched response with closingLedgerEntry and Lunar date', () {
      final model = LedgerAnnualAuditModel.fromJson({
        'auditId': 'AUD2026MATCH0001',
        'clanId': 'CLAN_DEFAULT',
        'auditYear': 2026,
        'nextPeriodYear': 2027,
        'auditDate': '2026-11-27T10:30:00Z',
        'systemBalance': 99800000.0,
        'actualBalance': 99800000.0,
        'discrepancyAmount': 0.0,
        'auditStatus': 'Matched',
        'referenceTransactionId': 'LDGMWYQDWK15F5JSY',
        'adjustmentRequestId': null,
        'closingTransactionId': 'LDG2026OPEN000001',
        'openingBalanceNextPeriod': 99800000.0,
        'auditorAccountId': 'ACC_TRUONG_TOC',
        'auditorDisplayName': 'Nguyễn Trọng Hoàng',
        'notes': 'Khớp 100%',
        'evidenceAttachmentUrl': '/api/v1/ledger/evidence/bb-2026.pdf',
        'createdAt': '2026-11-27T10:30:00Z',
        'closingLedgerEntry': {
          'transactionId': 'LDG2026OPEN000001',
          'clanId': 'CLAN_DEFAULT',
          'transactionType': 'OpeningBalanceCarryForward',
          'amount': 0.0,
          'runningBalance': 99800000.0,
          'description': 'Chốt đầu kỳ 2027',
          'previousHash':
              '8092d84cd50f51e38fc15ea98db9204566c3ace2d80ba105fee465ea422290d8',
          'recordHash':
              'a1b2c3d4e5f60718293a4b5c6d7e8f90123456789abcdef0123456789abcdef0',
          'createdAt': '2026-11-27T10:30:00Z',
        },
      });

      expect(model.isMatched, isTrue);
      expect(model.isSurplus, isFalse);
      expect(model.isShortage, isFalse);
      expect(model.effectiveAuditorName, 'Nguyễn Trọng Hoàng');
      expect(model.closingTransactionId, 'LDG2026OPEN000001');
      expect(
        model.closingLedgerEntry?.transactionType,
        LedgerTransactionTypeEnum.openingBalanceCarryForward,
      );
      expect(model.formattedLunarDate, contains('ÂL'));
    });

    test('parses DiscrepancyDetected response with US-15 adjustment request',
        () {
      final model = LedgerAnnualAuditModel.fromJson({
        'auditId': 'AUD2026DISC0002',
        'clanId': 'CLAN_DEFAULT',
        'auditYear': 2026,
        'nextPeriodYear': 2027,
        'auditDate': '2026-11-27T10:35:00Z',
        'systemBalance': 99800000.0,
        'actualBalance': 98000000.0,
        'discrepancyAmount': -1800000.0,
        'auditStatus': 'DiscrepancyDetected',
        'referenceTransactionId': 'LDGMWYQDWK15F5JSY',
        'adjustmentRequestId': 'LAR2026AUD00002',
        'auditorAccountId': 'ACC_TRUONG_TOC',
        'createdAt': '2026-11-27T10:35:00Z',
        'autoGeneratedAdjustmentRequest': {
          'requestId': 'LAR2026AUD00002',
          'originalTransactionId': 'LDGMWYQDWK15F5JSY',
          'clanId': 'CLAN_DEFAULT',
          'originalTransactionType': 'CommonFundDisbursement',
          'originalTransactionAmount': -15000000.0,
          'proposedAdjustmentAmount': -1800000.0,
          'adjustmentReason': 'Tự động sinh từ kiểm kê định kỳ năm 2026',
          'proposedByAccountId': 'ACC_TRUONG_TOC',
          'approvalStatus': 'Pending',
          'createdAt': '2026-11-27T10:35:00Z',
        },
      });

      expect(model.isMatched, isFalse);
      expect(model.isShortage, isTrue);
      expect(model.isSurplus, isFalse);
      expect(model.discrepancyAmount, -1800000.0);
      expect(model.adjustmentRequestId, 'LAR2026AUD00002');
      expect(
        model.autoGeneratedAdjustmentRequest?.approvalStatus,
        LedgerAdjustmentStatusEnum.pending,
      );
      expect(model.effectiveAuditorName, 'ACC_TRUONG_TOC');
    });
  });
}
